@register.simple_tag
def icon(name, size=18, **kwargs):
    paths = ICONS.get(name)
    if paths is None:
        raise template.TemplateSyntaxError(f"Unknown icon {name!r}")
    css = "icon " + kwargs.get("class", "")
    return format_html(
        '<svg class="{}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{}</svg>',
        css.strip(), size, size, mark_safe(paths),
    )


STATUS_TONES = {
    "DRAFT": "neutral", "SENT": "info", "QUERY": "warning", "CONFIRMED": "success", "REJECTED": "danger", "CLOSED": "muted",
}


@register.filter
def status_tone(status):
    return STATUS_TONES.get(status, "neutral")


@register.filter
def initials(user):
    name = (user.get_full_name() or user.get_username() or "?").strip()
    parts = name.split()
    return (parts[0][0] + (parts[-1][0] if len(parts) > 1 else "")).upper()


@register.filter
def action_label(action):
    """MARKED_CONFIRMED -> "Marked confirmed" (audit log action codes for display)."""
    text = (action or "").replace("_", " ").strip().lower()
    return text[:1].upper() + text[1:]


@register.filter
def ago(value):
    """Short relative time: "4 hours ago" (one unit, unlike |timesince)."""
    if not value:
        return ""
    from django.utils.timesince import timesince

    return f"{timesince(value, depth=1)} ago"
